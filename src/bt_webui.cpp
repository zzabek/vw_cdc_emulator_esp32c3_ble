static void appendJsonEscaped(String& out, const char* text) {
    for (size_t i = 0; text[i] != '\0'; i++) {
        char ch = text[i];
        if (ch == '"' || ch == '\\') {
            out += '\\';
            out += ch;
        } else if ((uint8_t)ch >= 0x20) {
            out += ch;
        }
    }
}

