static void registerApiRoutes() {
    s_webServer.on("/api/state", HTTP_GET, [](AsyncWebServerRequest* req) {
        sendJson(req, 200, buildStateJson());
    });

    s_webServer.on("/api/dump", HTTP_GET, [](AsyncWebServerRequest* req) {
        sendText(req, 200, buildDiagDump());
    });

    s_webServer.on("/api/ota/info", HTTP_GET, [](AsyncWebServerRequest* req) {
        sendJson(req, 200, buildOtaInfoJson());
    });

    s_webServer.on("/api/ota/rollback", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        if (!Update.canRollBack()) {
            sendText(req, 400, "No valid previous OTA firmware partition available");
            return;
        }
        s_rollbackReq = true;
        AsyncWebServerResponse* res = req->beginResponse(
            200, "text/plain", "Rolling back to previous firmware and rebooting...");
        res->addHeader("Cache-Control", "no-store");
        res->addHeader("Connection", "close");
        req->send(res);
    });

    s_webServer.on("/api/btns/save", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        String rowsPayload;
        if (!getReqParam(req, "rows", rowsPayload)) {
            sendText(req, 400, "Missing 'rows' payload");
            return;
        }
        CmdEntry entries[CMD_MAP_MAX_ENTRIES];
        size_t   count = 0;
        if (!parseRowsPayload(rowsPayload, entries, count)) {
            sendText(req, 400, "Invalid button table entry (check hex codes)");
            return;
        }
        btnMap_replaceAll(entries, count);
        sendText(req, 200, "Saved " + String((unsigned)count) + " button mappings");
    });

    s_webServer.on("/api/btn/delete", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        String codeStr;
        uint8_t cmdCode = 0;
        if (!getReqParam(req, "code", codeStr) || !parseHex8(codeStr, cmdCode)) {
            sendText(req, 400, "Invalid packet code");
            return;
        }
        if (btnMap_remove(cmdCode)) {
            sendText(req, 200, "Removed packet " + codeStr);
        } else {
            sendText(req, 404, "Packet not found");
        }
    });

    s_webServer.on("/api/btn/reset", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        btnMap_clearAll();
        sendText(req, 200, "Cleared all mappings");
    });

    s_webServer.on("/api/keepalive", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        String enStr, msStr, hidStr;
        if (!getReqParam(req, "en", enStr) ||
            !getReqParam(req, "ms", msStr) ||
            !getReqParam(req, "hid", hidStr)) {
            sendText(req, 400, "Missing keepalive parameters");
            return;
        }

        uint16_t hidCode = 0;
        if (!parseHex16(hidStr, hidCode)) {
            sendText(req, 400, "Invalid keepalive HID hex code");
            return;
        }

        KeepaliveConfig cfg = {};
        cfg.enabled    = (enStr == "1" || enStr == "true");
        cfg.intervalMs = (uint32_t)msStr.toInt();
        cfg.hidCode    = hidCode;

        if (!btnMap_setKeepalive(cfg)) {
            sendText(req, 400, "Invalid keepalive interval (1000..60000 ms) or HID code");
            return;
        }
        sendText(req, 200, cfg.enabled ? "Keepalive saved (ON)" : "Keepalive saved (OFF)");
    });

    s_webServer.on("/api/cmd", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        String codeStr;
        uint16_t code = 0;
        if (!getReqParam(req, "c", codeStr) ||
            !parseHex16(codeStr, code) ||
            !ble_hid_is_valid_code(code, false)) {
            sendText(req, 400, "Invalid HID code (valid: 0x0001..0x03FF or 0xF001..0xF018)");
            return;
        }
        if (!ble_hid_is_connected()) {
            sendText(req, 200, "Not sent - BLE is disconnected");
            return;
        }
        if (s_bleQ) xQueueSend(s_bleQ, &code, 0);
        sendText(req, 200, "Sent " + codeStr);
    });

    s_webServer.on("/api/tadv", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        s_tadvReq = true;
        bool targetAdv = !ble_hid_is_advertising();
        sendText(req, 200, targetAdv ? "Starting advertising..." : "Stopping advertising...");
    });

    s_webServer.on("/api/prefix", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        s_prefixReq = true;
        bool target = !ble_hid_get_prefix();
        sendText(req, 200, target ? "Report ID prefix -> ON" : "Report ID prefix -> OFF");
    });

    s_webServer.on("/api/delbonds", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (rejectIfOtaActive(req)) return;
        s_delBondsReq = true;
        sendText(req, 200, "Deleting BLE bonds, rebooting in ~1s...");
    });
}

static void registerOtaRoutes() {
    s_webServer.on("/update", HTTP_POST,
        [](AsyncWebServerRequest* req) {
            bool   isConflict = false;
            bool   hasOwner   = false;
            bool   ok         = false;
            String errMsg;

            if (s_otaMutex) xSemaphoreTake(s_otaMutex, portMAX_DELAY);
            if (s_ota.active && s_otaOwnerReq != req) {
                isConflict = true;
            } else if (s_otaOwnerReq == req) {
                hasOwner = true;
                ok       = s_ota.finishedOk && !Update.hasError();
                if (!ok) {
                    errMsg = (s_ota.errorMsg[0] != '\0')
                           ? String(s_ota.errorMsg)
                           : String("ERROR: Flash write or verification failed");
                    otaCleanupLocked(true);
                }
                s_otaOwnerReq = nullptr;
            }
            if (s_otaMutex) xSemaphoreGive(s_otaMutex);

            if (isConflict) {
                sendText(req, 409, "Another OTA upload is already in progress");
                return;
            }
            if (!hasOwner) {
                sendText(req, 400, "No firmware file uploaded");
                return;
            }

            AsyncWebServerResponse* res = req->beginResponse(
                ok ? 200 : 400, "text/plain",
                ok ? String("OK - Firmware verified. Rebooting...") : errMsg);
            res->addHeader("Connection", "close");
            req->send(res);
        },
        [](AsyncWebServerRequest* req, const String& filename, size_t index,
           uint8_t* data, size_t len, bool final) {
            if (s_otaMutex) xSemaphoreTake(s_otaMutex, portMAX_DELAY);

            if (s_ota.active && s_otaOwnerReq != req) {
                if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                return;
            }

            if (index == 0) {
                memset(&s_ota, 0, sizeof(s_ota));
                s_ota.lastActivityMs = millis();
                s_ota.lastLogPct     = 101;
                s_otaOwnerReq        = req;

                req->onDisconnect([req]() {
                    if (s_otaMutex) xSemaphoreTake(s_otaMutex, portMAX_DELAY);
                    if (s_otaOwnerReq == req) {
                        s_otaOwnerReq = nullptr;
                        if (s_ota.active) {
                            Serial.println("[OTA] Client disconnected mid-upload - aborting");
                            snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                                     "Client disconnected mid-upload");
                            otaCleanupLocked(true);
                        }
                    }
                    if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                });

                Serial.printf("[OTA] Start: %s\n", filename.c_str());

                if (len == 0 || data == nullptr || data[0] != ESP_IMAGE_MAGIC_BYTE) {
                    snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                             "Invalid firmware image (missing 0xE9 ESP32 header)");
                    Serial.printf("[OTA] Rejected: %s\n", s_ota.errorMsg);
                    if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                    return;
                }

                String sizeStr;
                if (getReqParam(req, "size", sizeStr)) {
                    size_t parsedSize = 0;
                    size_t maxSpace   = ESP.getFreeSketchSpace();
                    if (!parseDecimalSize(sizeStr, parsedSize) ||
                        parsedSize < OTA_MIN_SIZE_BYTES ||
                        parsedSize > maxSpace) {
                        snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                                 "Invalid firmware size (%u..%u B allowed)",
                                 (unsigned)OTA_MIN_SIZE_BYTES, (unsigned)maxSpace);
                        Serial.printf("[OTA] Rejected: %s\n", s_ota.errorMsg);
                        if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                        return;
                    }
                    s_ota.expectedSize = parsedSize;
                }

                String md5Str;
                bool hasMd5 = false;
                if (getReqParam(req, "md5", md5Str)) {
                    md5Str.trim();
                    md5Str.toLowerCase();
                    if (!isValidMd5Hex(md5Str)) {
                        snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                                 "Invalid MD5 checksum format");
                        Serial.printf("[OTA] Rejected: %s\n", s_ota.errorMsg);
                        if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                        return;
                    }
                    hasMd5 = true;
                }

                cdc_pause(true);
                s_ota.pausedCdc = true;
                ble_hid_suspend(true);
                s_ota.suspendedBle = true;
                s_ota.active       = true;

                size_t beginSize = (s_ota.expectedSize > 0)
                                 ? s_ota.expectedSize
                                 : UPDATE_SIZE_UNKNOWN;
                if (!Update.begin(beginSize)) {
                    snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                             "Update.begin() failed: %s", Update.errorString());
                    Serial.printf("[OTA] %s\n", s_ota.errorMsg);
                    otaCleanupLocked(true);
                    if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                    return;
                }

                if (hasMd5 && !Update.setMD5(md5Str.c_str())) {
                    snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                             "Update.setMD5() failed");
                    Serial.printf("[OTA] %s\n", s_ota.errorMsg);
                    otaCleanupLocked(true);
                    if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                    return;
                }
            }

            if (s_otaOwnerReq != req || !s_ota.active) {
                if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                return;
            }

            s_ota.lastActivityMs = millis();

            if (s_ota.expectedSize > 0 && (s_ota.writtenBytes + len) > s_ota.expectedSize) {
                snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                         "Upload exceeded expected firmware size");
                Serial.printf("[OTA] %s\n", s_ota.errorMsg);
                otaCleanupLocked(true);
                if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                return;
            }

            if (len > 0) {
                if (Update.write(data, len) != len) {
                    snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                             "Flash write failed: %s", Update.errorString());
                    Serial.printf("[OTA] %s\n", s_ota.errorMsg);
                    otaCleanupLocked(true);
                    if (s_otaMutex) xSemaphoreGive(s_otaMutex);
                    return;
                }
                s_ota.writtenBytes += len;
            }

            size_t total = (s_ota.expectedSize > 0) ? s_ota.expectedSize : req->contentLength();
            if (total > 0 && len > 0) {
                size_t pct = (s_ota.writtenBytes * 100U) / total;
                if (pct > 100U) pct = 100U;
                if (pct != s_ota.lastLogPct && (pct % 10U) == 0U) {
                    s_ota.lastLogPct = pct;
                    Serial.printf("[OTA] %u%%\n", (unsigned)pct);
                }
            }

            if (final) {
                if (s_ota.writtenBytes < OTA_MIN_SIZE_BYTES) {
                    snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                             "Firmware too small (%u B)", (unsigned)s_ota.writtenBytes);
                    Serial.printf("[OTA] %s\n", s_ota.errorMsg);
                    otaCleanupLocked(true);
                } else if (s_ota.expectedSize > 0 && s_ota.writtenBytes != s_ota.expectedSize) {
                    snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                             "Truncated upload (%u/%u B)",
                             (unsigned)s_ota.writtenBytes, (unsigned)s_ota.expectedSize);
                    Serial.printf("[OTA] %s\n", s_ota.errorMsg);
                    otaCleanupLocked(true);
                } else {
                    bool ok = Update.end(s_ota.expectedSize == 0);
                    Serial.printf("[OTA] Done: %s (%u bytes)\n",
                                  ok ? "SUCCESS" : Update.errorString(),
                                  (unsigned)s_ota.writtenBytes);
                    if (ok) {
                        s_ota.finishedOk   = true;
                        otaCleanupLocked(false);
                        s_otaRebootStartMs = 0;
                        s_otaReboot        = true;
                    } else {
                        snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg),
                                 "Verification failed: %s", Update.errorString());
                        otaCleanupLocked(true);
                    }
                }
            }

            if (s_otaMutex) xSemaphoreGive(s_otaMutex);
        });
}

