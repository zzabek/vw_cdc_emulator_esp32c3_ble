static bool parseRowsPayload(const String& payload, CmdEntry* outEntries, size_t& outCount) {
    outCount = 0;
    int pos = 0;
    int totalLen = payload.length();

    while (pos < totalLen && outCount < CMD_MAP_MAX_ENTRIES) {
        int lineEnd = payload.indexOf('\n', pos);
        if (lineEnd < 0) lineEnd = totalLen;

        String line = payload.substring(pos, lineEnd);
        line.trim();
        pos = lineEnd + 1;

        if (line.length() == 0) continue;

        int t1 = line.indexOf('\t');
        int t2 = (t1 >= 0) ? line.indexOf('\t', t1 + 1) : -1;
        int t3 = (t2 >= 0) ? line.indexOf('\t', t2 + 1) : -1;
        int t4 = (t3 >= 0) ? line.indexOf('\t', t3 + 1) : -1;
        if (t1 < 0 || t2 < 0 || t3 < 0 || t4 < 0) {
            return false;
        }

        uint8_t  cmdCode = 0;
        uint16_t hidCode = 0;
        if (!parseHex8(line.substring(0, t1), cmdCode)) return false;
        if (!parseHex16(line.substring(t2 + 1, t3), hidCode) ||
            !ble_hid_is_valid_code(hidCode, true)) {
            return false;
        }

        int actVal   = line.substring(t3 + 1, t4).toInt();
        int paramVal = line.substring(t4 + 1).toInt();
        if (actVal < 0 || actVal > (int)RadioAction::RANDOM_TOGGLE) return false;

        CmdEntry entry = {};
        entry.cmdCode     = cmdCode;
        entry.hidCode     = hidCode;
        entry.radioAction = (RadioAction)actVal;
        entry.actionParam = (uint8_t)((paramVal >= 0 && paramVal <= 255) ? paramVal : 0);

        String name = line.substring(t1 + 1, t2);
        name.trim();
        strncpy(entry.name, name.c_str(), sizeof(entry.name) - 1);
        entry.name[sizeof(entry.name) - 1] = '\0';

        outEntries[outCount++] = entry;
    }
    return true;
}

