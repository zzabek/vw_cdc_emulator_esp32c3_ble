void btWebUI_init() {
    MDNS.begin(DEVICE_MDNS_HOST);
    s_bleQ     = xQueueCreate(8, sizeof(uint16_t));
    s_otaMutex = xSemaphoreCreateMutex();
    memset(&s_ota, 0, sizeof(s_ota));
    s_otaOwnerReq      = nullptr;
    s_otaReboot        = false;
    s_otaRebootStartMs = 0;
    s_rollbackReq      = false;

    registerStaticRoutes();
    registerApiRoutes();
    registerOtaRoutes();
    s_webServer.onNotFound([](AsyncWebServerRequest* req) {
        sendText(req, 404, "404 Not Found");
    });

    s_webServer.begin();
    Serial.println("[WEBUI] AsyncWebServer ready (embedded web UI + hardened OTA)");
}

void btWebUI_loop() {
    // 1. Manual OTA rollback to previous bootable partition
    if (s_rollbackReq && !s_ota.active) {
        s_rollbackReq = false;
        Serial.println("[OTA] Rolling back to previous partition...");
        cdc_pause(true);
        bool ok = Update.rollBack();
        cdc_pause(false);
        if (ok) {
            delay(300);
            ESP.restart();
        } else {
            Serial.println("[OTA] Rollback failed - no valid alternate partition");
        }
    }

    // 2. Delete BLE bonds + restart safely outside AsyncTCP context
    if (s_delBondsReq) {
        s_delBondsReq = false;
        Serial.println("[WEBUI] Deleting BLE bonds...");
        cdc_pause(true);
        ble_hid_delete_bonds();
        cdc_pause(false);
        delay(500);
        Serial.println("[WEBUI] Restarting ESP");
        ESP.restart();
    }

    // 3. Toggle BLE advertising outside AsyncTCP callback
    if (s_tadvReq) {
        s_tadvReq = false;
        if (ble_hid_is_advertising()) ble_hid_stop_advertising();
        else                          ble_hid_start_advertising();
    }

    // 4. Toggle Report ID prefix + commit NVS safely
    if (s_prefixReq) {
        s_prefixReq = false;
        cdc_pause(true);
        ble_hid_set_prefix(!ble_hid_get_prefix());
        cdc_pause(false);
    }

    // 5. Drain queued manual HID test commands (each holds 50 ms)
    uint16_t code = 0;
    while (s_bleQ && xQueueReceive(s_bleQ, &code, 0) == pdTRUE) {
        ble_hid_send_button(code);
    }

    // 7. OTA stall watchdog: abort stalled upload after 20 s and restore CDC/BLE
    if (s_otaMutex) xSemaphoreTake(s_otaMutex, portMAX_DELAY);
    if (s_ota.active && (millis() - s_ota.lastActivityMs > OTA_STALL_TIMEOUT_MS)) {
        Serial.println("[OTA] Watchdog timeout - aborting stalled upload");
        snprintf(s_ota.errorMsg, sizeof(s_ota.errorMsg), "Upload stalled (20s timeout)");
        otaCleanupLocked(true);
        s_otaOwnerReq = nullptr;
    }
    if (s_otaMutex) xSemaphoreGive(s_otaMutex);

    // 8. Delayed reboot after OTA HTTP response finishes flushing
    if (s_otaReboot) {
        if (s_otaRebootStartMs == 0) {
            s_otaRebootStartMs = millis();
            Serial.println("[OTA] Rebooting in ~1s...");
        }
        if (millis() - s_otaRebootStartMs > 1000U) {
            ESP.restart();
        }
    }
}
