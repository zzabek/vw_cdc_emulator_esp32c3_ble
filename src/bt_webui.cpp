static bool isHexDigitChar(char ch) {
    return (ch >= '0' && ch <= '9') ||
           (ch >= 'a' && ch <= 'f') ||
           (ch >= 'A' && ch <= 'F');
}

static bool parseHexValue(const String& in, uint32_t& out, uint8_t maxDigits) {
    String s = in;
    s.trim();
    if (s.length() > 2 && s[0] == '0' && (s[1] == 'x' || s[1] == 'X')) {
        s = s.substring(2);
    }
    if (s.length() < 1 || s.length() > maxDigits) return false;
    for (unsigned i = 0; i < s.length(); i++) {
        if (!isHexDigitChar(s[i])) return false;
    }
    out = (uint32_t)strtoul(s.c_str(), nullptr, 16);
    return true;
}

static bool parseHex8(const String& in, uint8_t& out) {
    uint32_t val = 0;
    if (!parseHexValue(in, val, 2) || val > 0xFFU) return false;
    out = (uint8_t)val;
    return true;
}

static bool parseHex16(const String& in, uint16_t& out) {
    uint32_t val = 0;
    if (!parseHexValue(in, val, 4) || val > 0xFFFFU) return false;
    out = (uint16_t)val;
    return true;
}

static bool parseDecimalSize(const String& in, size_t& out) {
    String s = in;
    s.trim();
    if (s.length() == 0 || s.length() > 10) return false;
    uint64_t acc = 0;
    for (unsigned i = 0; i < s.length(); i++) {
        if (s[i] < '0' || s[i] > '9') return false;
        acc = acc * 10ULL + (uint64_t)(s[i] - '0');
        if (acc > 0xFFFFFFFFULL) return false;
    }
    out = (size_t)acc;
    return true;
}

static bool isValidMd5Hex(const String& in) {
    if (in.length() != 32) return false;
    for (unsigned i = 0; i < 32; i++) {
        if (!isHexDigitChar(in[i])) return false;
    }
    return true;
}

static bool getReqParam(AsyncWebServerRequest* req, const char* name, String& out) {
    const AsyncWebParameter* p = req->getParam(name, true);
    if (!p) p = req->getParam(name, false);
    if (!p) return false;
    out = p->value();
    return true;
}

static void serveEmbeddedAsset(AsyncWebServerRequest* req, const char* contentType,
                               const uint8_t* start, const uint8_t* end) {
    size_t len = (size_t)(end - start);
    if (len > 0 && start[len - 1] == '\0') {
        len--;
    }
    AsyncWebServerResponse* res = req->beginResponse(200, contentType, start, len);
    res->addHeader("Cache-Control", "no-store");
    req->send(res);
}

static void sendText(AsyncWebServerRequest* req, int statusCode, const String& body) {
    AsyncWebServerResponse* res = req->beginResponse(statusCode, "text/plain", body);
    res->addHeader("Cache-Control", "no-store");
    req->send(res);
}

static void sendJson(AsyncWebServerRequest* req, int statusCode, const String& body) {
    AsyncWebServerResponse* res = req->beginResponse(statusCode, "application/json", body);
    res->addHeader("Cache-Control", "no-store");
    req->send(res);
}

static bool rejectIfOtaActive(AsyncWebServerRequest* req) {
    if (s_ota.active) {
        sendText(req, 503, "OTA update in progress - try again after completion");
        return true;
    }
    return false;
}

// Must be called with s_otaMutex held (or before AsyncWebServer starts)
static void otaCleanupLocked(bool abortUpdate) {
    if (abortUpdate && Update.isRunning()) {
        Update.abort();
    }
    if (s_ota.pausedCdc) {
        cdc_pause(false);
        s_ota.pausedCdc = false;
    }
    if (s_ota.suspendedBle) {
        ble_hid_suspend(false);
        s_ota.suspendedBle = false;
    }
    s_ota.active = false;
}

